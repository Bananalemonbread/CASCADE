namespace Calc;

public class Calculator
{
    /// <summary>
    /// Adds two integers.
    /// </summary>
    public int Add(int a, int b)
    {
        return a + b;
    }

    /// <summary>
    /// Subtracts the second integer from the first integer.
    /// </summary>
    public int Sub(int a, int b)
    {
        return a - b;
    }

    /// <summary>
    /// Multiplies two integers.
    /// </summary>
    public int Mul(int a, int b)
    {
        return a / b;
    }
}
